CREATE TABLE IF NOT EXISTS patient_encounters (
    encounter_id BIGINT PRIMARY KEY,
    patient_nbr BIGINT NOT NULL,
    age VARCHAR(30) NOT NULL,
    time_in_hospital INTEGER,
    number_inpatient INTEGER,
    number_emergency INTEGER,
    number_outpatient INTEGER,
    num_medications INTEGER,
    num_lab_procedures INTEGER,
    num_procedures INTEGER,
    admission_type_id INTEGER,
    discharge_disposition_id INTEGER,
    readmitted VARCHAR(10),
    risk_score INTEGER NOT NULL,
    risk_level VARCHAR(20) NOT NULL,
    review_reason TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT valid_risk_level CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH'))

);

CREATE TABLE IF NOT EXISTS care_interventions (
    intervention_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING REVIEW',
    assigned_to VARCHAR(100),
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_encounter FOREIGN KEY (encounter_id) REFERENCES patient_encounters(encounter_id)
);

ALTER TABLE patient_encounters
    ADD COLUMN IF NOT EXISTS num_procedures INTEGER;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'care_interventions'
          AND column_name = 'intervention_id'
          AND is_identity = 'YES'
    ) THEN
        ALTER TABLE care_interventions
            ALTER COLUMN intervention_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;

SELECT setval(
    pg_get_serial_sequence('care_interventions', 'intervention_id'),
    COALESCE(MAX(intervention_id), 1),
    COUNT(*) > 0
)
FROM care_interventions;